    # quick manual check
    import json
    for fname in ["Transcript_1_France.txt", "Transcript_2_Germany.txt", "Transcript_3_UK.txt"]:
        turns = parse_transcript(os.path.join(os.path.dirname(__file__), "..", "data", fname))
        print(f"\n--- {fname}: {len(turns)} turns ---")
        for t in turns[:3]:
            print(json.dumps(t.to_dict(), indent=2))
    qs = parse_interview_guide(os.path.join(os.path.dirname(__file__), "..", "data", "Interview_Guide.txt"))
